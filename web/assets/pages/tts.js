import { api, stream, uploadFile } from "../api.js";
import {
  emptyState,
  escapeHtml,
  icon,
  setButtonBusy,
  spinner,
  toast,
} from "../ui.js";

export async function renderTTS(root, ctx) {
  const boot = ctx.boot;
  const models = boot.audio_models || [];
  let modelId = boot.default_audio_model || models[0]?.id || "";
  let voices = [];
  let reference = null;
  let referenceTranscript = "";
  let voiceName = "";
  let running = false;
  let controller = null;
  let result = null;
  let statusText = boot.audio_status || "audio.cpp server not running.";
  let phaseText = "";

  root.innerHTML = `
    <div class="grid items-start gap-5 xl:grid-cols-[minmax(0,1fr)_24rem]">
      <div class="min-w-0 space-y-5">
        <section class="card">
          <div class="card-header">
            <div class="flex items-center gap-2.5">
              <span class="flex h-8 w-8 items-center justify-center rounded-lg bg-fuchsia-500/10 text-fuchsia-300">${icon("mic", "h-4 w-4")}</span>
              <div>
                <h2 class="card-title">Speech</h2>
                <p class="card-subtitle">Generated by a local audio.cpp server</p>
              </div>
            </div>
            <span class="chip ${boot.audio_loaded ? "chip-success" : ""}" data-model-chip>${boot.audio_loaded ? "Running" : "Idle"}</span>
          </div>
          <div class="space-y-4 p-4 sm:p-5">
            ${
              models.length
                ? `<div class="flex flex-col gap-2 sm:flex-row">
                    <select class="select min-w-0 flex-1" data-model aria-label="Text to speech model">
                      ${models
                        .map(
                          (model) =>
                            `<option value="${escapeHtml(model.id)}" ${model.id === modelId ? "selected" : ""}>${escapeHtml(model.alias)}</option>`,
                        )
                        .join("")}
                    </select>
                    <div class="flex shrink-0 gap-2">
                      <button class="btn-secondary btn-xs" data-load>${icon("play", "h-3.5 w-3.5")} Load</button>
                      <button class="btn-ghost btn-xs" data-unload>${icon("stop", "h-3.5 w-3.5")} Unload</button>
                    </div>
                  </div>`
                : `<div class="rounded-xl border border-amber-400/20 bg-amber-400/10 p-3 text-sm text-amber-200">No audio.cpp models configured. Add entries to <code class="font-mono">configs/audio_models.json</code>.</div>`
            }
            <p class="rounded-lg border border-subtle bg-raised px-3 py-2 text-[11px] leading-5 text-slate-500" data-status>${escapeHtml(statusText)}</p>
            <div>
              <label class="label" for="tts-text">Text</label>
              <textarea id="tts-text" class="textarea min-h-[9rem]" rows="6" data-text placeholder="Type the text to speak…"></textarea>
            </div>
            <div class="grid gap-3 sm:grid-cols-[minmax(0,1fr)_15rem]">
              <div>
                <label class="label" for="tts-voice">Voice</label>
                <select id="tts-voice" class="select" data-voice aria-label="Voice"></select>
                <p class="mt-1 text-[11px] text-slate-500">Load the model or refresh to list its voices.</p>
              </div>
              <div>
                <div class="flex items-center justify-between gap-2"><label class="label" for="tts-speed">Speed</label><span class="text-[11px] font-mono text-slate-500" data-speed-label>1.00×</span></div>
                <div class="flex items-center gap-2">
                  <input id="tts-speed" type="range" class="range min-w-0 flex-1" min="0.5" max="2" step="0.05" value="1" data-speed />
                  <input type="number" class="input w-20 shrink-0 text-right font-mono text-xs" min="0.5" max="2" step="0.05" value="1" data-speed-number />
                </div>
                <p class="mt-1 text-[11px] text-slate-500">Some models only accept 1.0.</p>
              </div>
            </div>
            <div class="flex flex-wrap items-center gap-2">
              <button class="btn-secondary btn-xs" data-refresh-voices>${icon("refresh", "h-4 w-4")} Refresh voices</button>
              <span class="text-[11px] text-slate-500" data-voice-status>Voices are listed from the running server.</span>
            </div>
          </div>
        </section>

        <section class="card">
          <details class="group">
            <summary class="card-header cursor-pointer list-none select-none">
              <div class="flex items-center gap-2.5">
                <span class="flex h-8 w-8 items-center justify-center rounded-lg bg-amber-500/10 text-amber-300">${icon("wand", "h-4 w-4")}</span>
                <div>
                  <h2 class="card-title">Voice cloning & advanced</h2>
                  <p class="card-subtitle">Optional reference clip and sampler controls</p>
                </div>
              </div>
              <span class="text-slate-500 transition group-open:rotate-180">${icon("chevron", "h-4 w-4")}</span>
            </summary>
            <div class="space-y-4 border-t border-subtle p-4 sm:p-5">
              <div class="rounded-xl border border-subtle bg-raised p-3" data-ref-panel></div>
              <div class="grid gap-3 sm:grid-cols-2">
                <div>
                  <label class="label" for="tts-seed">Seed</label>
                  <input id="tts-seed" type="number" class="input font-mono text-xs" value="0" step="1" data-seed />
                </div>
                <div>
                  <label class="label" for="tts-max-tokens">Max tokens</label>
                  <input id="tts-max-tokens" type="number" class="input font-mono text-xs" value="0" step="1" data-max-tokens />
                  <p class="mt-1 text-[11px] text-slate-500">0 uses the model default.</p>
                </div>
              </div>
            </div>
          </details>
        </section>

        <section class="card">
          <div class="space-y-3 p-4 sm:p-5">
            <div class="flex flex-wrap gap-2">
              <button class="btn-primary min-w-[9rem] flex-1" data-generate ${models.length ? "" : "disabled"}>${icon("play", "h-4 w-4")} Generate speech</button>
              <button class="btn-danger min-w-[7rem] flex-1" data-stop disabled>${icon("stop", "h-4 w-4")} Stop</button>
            </div>
            <div class="hidden items-center gap-2 text-xs text-slate-400" data-phase-wrap>
              ${spinner("h-3.5 w-3.5")}
              <span data-phase>Generating…</span>
            </div>
          </div>
        </section>
      </div>

      <aside class="min-w-0 space-y-5 xl:sticky xl:top-24 xl:self-start">
        <section class="card overflow-hidden">
          <div class="card-header">
            <div class="flex items-center gap-2.5">
              <span class="flex h-8 w-8 items-center justify-center rounded-lg bg-emerald-500/10 text-emerald-300">${icon("volume", "h-4 w-4")}</span>
              <div>
                <h2 class="card-title">Output</h2>
                <p class="card-subtitle" data-result-subtitle>No speech generated yet.</p>
              </div>
            </div>
            <a class="btn-ghost btn-xs hidden" data-download download>${icon("download", "h-4 w-4")} Download</a>
          </div>
          <div class="p-4 sm:p-5" data-result></div>
        </section>
      </aside>
    </div>
  `;

  const $ = (selector) => root.querySelector(selector);
  const modelSelect = $("[data-model]");
  const voiceInput = $("[data-voice]");
  const status = $("[data-status]");
  const modelChip = $("[data-model-chip]");
  const phaseWrap = $("[data-phase-wrap]");
  const phaseLabel = $("[data-phase]");
  const resultEl = $("[data-result]");
  const resultSubtitle = $("[data-result-subtitle]");
  const download = $("[data-download]");
  const generateButton = $("[data-generate]");
  const stopButton = $("[data-stop]");
  const speedRange = $("[data-speed]");
  const speedNumber = $("[data-speed-number]");
  const speedLabel = $("[data-speed-label]");
  const textInput = $("[data-text]");

  function setStatus(text, running) {
    statusText = text;
    status.textContent = text;
    if (running !== undefined) {
      modelChip.textContent = running ? "Running" : "Idle";
      modelChip.className = `chip ${running ? "chip-success" : ""}`;
    }
  }

  function renderVoices() {
    if (!voices.length) {
      voiceInput.innerHTML = '<option value="">Default voice</option>';
      voiceInput.disabled = true;
    } else {
      voiceInput.disabled = false;
      const previous = voiceInput.value;
      const selected = voices.includes(previous) ? previous : voices[0];
      voiceInput.innerHTML = voices
        .map(
          (voice) =>
            `<option value="${escapeHtml(voice)}" ${voice === selected ? "selected" : ""}>${escapeHtml(voice)}</option>`,
        )
        .join("");
      voiceInput.value = selected;
    }
    $("[data-voice-status]").textContent = voices.length
      ? `${voices.length} voice${voices.length === 1 ? "" : "s"} available.`
      : "Voices are listed from the running server.";
  }

  function renderResult() {
    if (!result) {
      download.classList.add("hidden");
      resultSubtitle.textContent = "No speech generated yet.";
      resultEl.innerHTML = emptyState(
        "Your audio will appear here",
        "Enter some text and press Generate speech. The local model starts automatically on the first run.",
        "volume",
      );
      return;
    }
    download.href = result.url;
    download.classList.remove("hidden");
    resultSubtitle.textContent = result.filename || "Generated speech";
    resultEl.innerHTML = `
      <div class="rounded-2xl border border-subtle bg-raised p-5">
        <div class="mb-4 flex items-center gap-3">
          <span class="flex h-10 w-10 items-center justify-center rounded-xl bg-emerald-500/10 text-emerald-300">${icon("volume", "h-5 w-5")}</span>
          <div class="min-w-0">
            <p class="truncate text-sm font-medium text-slate-200">${escapeHtml(result.filename || "Generated speech")}</p>
            <p class="text-xs text-slate-500">audio.cpp</p>
          </div>
        </div>
        <audio class="w-full" controls autoplay src="${escapeHtml(result.url)}"></audio>
      </div>
    `;
  }

  function setRunning(value) {
    running = value;
    generateButton.disabled = value || !models.length;
    generateButton.innerHTML = value
      ? `${spinner("h-4 w-4")} Generating…`
      : `${icon("play", "h-4 w-4")} Generate speech`;
    stopButton.disabled = !value;
    phaseWrap.classList.toggle("hidden", !value);
  }

  async function loadModel() {
    if (!modelId) return;
    const button = $("[data-load]");
    setButtonBusy(button, true, "Loading…");
    try {
      const data = await api("/api/audio/load", {
        method: "POST",
        body: { model_id: modelId },
      });
      voices = data.voices || [];
      renderVoices();
      setStatus(data.status, data.loaded);
      toast("Audio model loaded.", "success");
    } catch (error) {
      toast(error.message, "error");
    } finally {
      setButtonBusy(button, false);
    }
  }

  async function unloadModel() {
    const button = $("[data-unload]");
    setButtonBusy(button, true, "Stopping…");
    try {
      const data = await api("/api/audio/unload", { method: "POST" });
      voices = [];
      renderVoices();
      setStatus(data.status, data.loaded);
      toast("audio.cpp server stopped.", "success");
    } catch (error) {
      toast(error.message, "error");
    } finally {
      setButtonBusy(button, false);
    }
  }

  async function refreshVoices() {
    if (!modelId) return;
    const button = $("[data-refresh-voices]");
    setButtonBusy(button, true, "Loading…");
    try {
      const data = await api(`/api/audio/voices?model_id=${encodeURIComponent(modelId)}`);
      voices = data.voices || [];
      renderVoices();
      setStatus("audio.cpp server running.", true);
      toast(`Loaded ${voices.length} voice${voices.length === 1 ? "" : "s"}.`, "success");
    } catch (error) {
      toast(error.message, "error");
    } finally {
      setButtonBusy(button, false);
    }
  }

  async function saveVoice() {
    if (!reference) return toast("Upload a reference clip first.", "warning");
    const name = voiceName.trim();
    if (!name) return toast("Give the voice a name first.", "warning");
    const button = $("[data-save-voice]");
    setButtonBusy(button, true, "Saving…");
    try {
      const data = await api("/api/audio/save-voice", {
        method: "POST",
        body: {
          model_id: modelId,
          name,
          upload: reference.id,
          transcript: referenceTranscript,
        },
      });
      voices = data.voices || [];
      renderVoices();
      voiceInput.value = data.name;
      voiceName = "";
      renderReferencePanel();
      toast(data.status, "success");
    } catch (error) {
      toast(error.message, "error");
    } finally {
      setButtonBusy(button, false);
    }
  }

  async function generate() {
    if (running || !modelId) return;
    const text = textInput.value.trim();
    if (!text) return toast("Type the text to speak first.", "warning");
    setRunning(true);
    phaseLabel.textContent = "Starting audio.cpp…";
    result = null;
    renderResult();
    controller = new AbortController();

    try {
      await stream(
        "/api/audio/generate",
        {
          model_id: modelId,
          text,
          voice: voiceInput.value || null,
          speed: Number(speedNumber.value) || 1,
          seed: Number($("[data-seed]").value) || 0,
          max_tokens: Number($("[data-max-tokens]").value) || 0,
          voice_ref: reference?.id || null,
          reference_text: referenceTranscript,
        },
        (event) => {
          if (event.type === "phase") {
            phaseLabel.textContent = event.message;
          } else if (event.type === "result") {
            result = { ...event, filename: "generated-speech.wav" };
            renderResult();
          } else if (event.type === "error") {
            toast(event.message, "error");
          } else if (event.type === "done") {
            phaseLabel.textContent = "Done.";
          }
        },
        controller.signal,
      );
    } catch (error) {
      if (error.name !== "AbortError") toast(error.message, "error");
    } finally {
      setRunning(false);
      controller = null;
    }
  }

  async function stop() {
    try {
      await api("/api/audio/cancel", { method: "POST" });
      controller?.abort();
      toast("Stopping speech generation…", "warning", 1800);
    } catch (error) {
      toast(error.message, "error");
    }
  }

  modelSelect?.addEventListener("change", () => {
    modelId = modelSelect.value;
    voices = [];
    voiceInput.value = "";
    renderVoices();
  });
  $("[data-load]")?.addEventListener("click", loadModel);
  $("[data-unload]")?.addEventListener("click", unloadModel);
  $("[data-refresh-voices]")?.addEventListener("click", refreshVoices);
  generateButton.addEventListener("click", generate);
  stopButton.addEventListener("click", stop);

  speedRange.addEventListener("input", () => {
    speedNumber.value = speedRange.value;
    speedLabel.textContent = `${Number(speedRange.value).toFixed(2)}×`;
  });
  speedNumber.addEventListener("input", () => {
    const value = Math.min(2, Math.max(0.5, Number(speedNumber.value) || 1));
    speedRange.value = String(value);
    speedLabel.textContent = `${value.toFixed(2)}×`;
  });

  function renderReferencePanel() {
    const panel = $("[data-ref-panel]");
    if (!panel) return;
    panel.innerHTML = `
      <div class="flex flex-wrap items-center gap-2">
        <label class="btn-secondary btn-xs cursor-pointer">
          ${icon("upload", "h-3.5 w-3.5")} ${reference ? "Replace clip" : "Upload reference clip"}
          <input type="file" accept="audio/*" class="sr-only" data-ref-upload />
        </label>
        ${reference ? `<span class="min-w-0 flex-1 truncate text-[11px] text-slate-400">${escapeHtml(reference.name || "Reference clip")}</span>` : `<span class="text-[11px] text-slate-500">WAV, MP3, FLAC, OGG or M4A</span>`}
        ${reference ? `<button class="btn-ghost btn-xs text-rose-300 hover:bg-rose-500/10" data-ref-clear>${icon("trash", "h-3.5 w-3.5")}</button>` : ""}
      </div>
      ${reference ? `<audio class="mt-3 w-full" controls src="${escapeHtml(reference.url)}"></audio>` : ""}
      <textarea class="textarea mt-3 text-xs" rows="2" data-ref-text placeholder="What is said in the clip? (optional, improves cloning)">${escapeHtml(referenceTranscript)}</textarea>
      <div class="mt-3 flex flex-col gap-2 sm:flex-row">
        <input class="input min-w-0 flex-1" data-voice-name value="${escapeHtml(voiceName)}" placeholder="Save clip as voice, e.g. morgan" />
        <button class="btn-secondary btn-xs shrink-0" data-save-voice>${icon("save", "h-4 w-4")} Save voice</button>
      </div>
      <p class="mt-2 text-[11px] leading-5 text-slate-500">A reference clip overrides the Voice field. Saved voices are shared with the Chat page.</p>
    `;

    panel.querySelector("[data-ref-text]")?.addEventListener("input", (event) => {
      referenceTranscript = event.target.value;
    });
    panel.querySelector("[data-voice-name]")?.addEventListener("input", (event) => {
      voiceName = event.target.value;
    });
    panel.querySelector("[data-save-voice]")?.addEventListener("click", saveVoice);
    panel.querySelector("[data-ref-upload]")?.addEventListener("change", async (event) => {
      const file = event.target.files?.[0];
      event.target.value = "";
      if (!file) return;
      try {
        const stored = await uploadFile(file);
        reference = { id: stored.id, url: stored.url, name: stored.name };
        renderReferencePanel();
      } catch (error) {
        toast(error.message, "error");
      }
    });
    panel.querySelector("[data-ref-clear]")?.addEventListener("click", () => {
      reference = null;
      renderReferencePanel();
    });
  }

  renderReferencePanel();
  renderVoices();
  renderResult();
  setRunning(false);
  setStatus(statusText, boot.audio_loaded);

  return () => {
    if (running) {
      controller?.abort();
      api("/api/audio/cancel", { method: "POST" }).catch(() => {});
    }
  };
}
